"""The Threat's converted hulls - generator (2026-11-07).

Vanilla combat hulls the hive has reclaimed: each gets a Threat-palette sprite, a .skin that
bolts on the Threat's hullmods and engine style, and clones of its vanilla goal variants.
Everything this writes is regenerated from vanilla's files, so edit THIS script, not the
output. Run from anywhere:

    python tools/converted-hulls/gen.py            # write sprites, skins, variants, roles
    python tools/converted-hulls/gen.py --preview  # also tools/converted-hulls/preview.png

Writes:
  graphics/threatinc/ships/<hull>_conv.png             the recoloured sprite
  data/hulls/skins/threatinc_<hull>_conv.skin          skin: sprite, hullmods, THREAT engines
  data/variants/threatinc_converted/<variant>.variant  vanilla goal variants on the new hull
  data/world/factions/default_ship_roles.json          the threatincConverted* roles, between
                                                       the marker comments

Sprite recolour: the hull's luminance histogram is matched to vanilla's own Threat sprites
(so a bright high-tech hull and a dark low-tech one both land in the Threat's dark range),
each pixel is coloured from the Threat's luminance->colour ramp sampled from those sprites,
vanilla's faction paint (saturated areas) becomes the Threat's amber accent, a low-frequency
mottle breaks up flat plating, and a few mirrored amber glow nodes stand in for the hive's
hatches. Panel lines and shading survive because only brightness is remapped.
"""
import csv
import glob
import json
import os
import re
import sys

import numpy as np
from PIL import Image, ImageFilter

CORE = r"C:\Program Files (x86)\Fractal Softworks\Starsector\starsector-core"
MOD = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

PREFIX = "threatinc_"
SUFFIX = "_conv"
SPRITE_DIR = "graphics/threatinc/ships"
SKIN_DIR = "data/hulls/skins"
VARIANT_DIR = "data/variants/threatinc_converted"
ROLES_FILE = "data/world/factions/default_ship_roles.json"
ROLES_BEGIN = "\t# >>> converted hulls - GENERATED by tools/converted-hulls/gen.py, do not edit by hand"
ROLES_END = "\t# <<< converted hulls"

ROLE_BY_SIZE = {
    "FRIGATE": "threatincConvertedFrigate",
    "DESTROYER": "threatincConvertedDestroyer",
    "CRUISER": "threatincConvertedCruiser",
    "CAPITAL_SHIP": "threatincConvertedCapital",
}

# hulls the filter would pass that are not wanted: one-offs and the shuttle
EXCLUDE = {"shuttlepod", "ziggurat"}
EXCLUDE_TAGS = {"threat", "dweller", "omega", "remnant", "derelict", "station", "module", "shrouded"}
EXCLUDE_HINTS = {"CIVILIAN", "STATION", "UNBOARDABLE", "HIDE_IN_CODEX", "SHIP_WITH_MODULES"}
# built-ins that mark a hull as not a warship, or that the fragment swarm refuses
EXCLUDE_BUILTINS = {"phasefield", "civgrade"}

DESCRIPTION_PREFIX = (
    "Reclaimed by the Threat from a fleet it destroyed and rebuilt from the inside out. The "
    "hull and its armament are the original's; the crew spaces are packed with fabricator "
    "strata, and a fragment swarm roils in its voids. It answers only to the hive."
)

BUILT_IN_MODS = ["automated", "threat_hullmod", "fragment_swarm"]
TAGS = ["threat", "threat_combat", "threatinc_converted"]


# ---------------------------------------------------------------- vanilla files

def load_json(path):
    """Starsector's JSON: # comments and trailing commas allowed."""
    s = open(path, encoding="utf-8-sig").read()
    s = re.sub(r"(?m)#.*$", "", s)
    s = re.sub(r",\s*([}\]])", r"\1", s)
    return json.loads(s)


def vanilla_hulls():
    ships = {}
    for p in glob.glob(os.path.join(CORE, "data/hulls/*.ship")):
        j = load_json(p)
        ships[j["hullId"]] = j
    rows = []
    with open(os.path.join(CORE, "data/hulls/ship_data.csv"), encoding="utf-8-sig") as f:
        for r in csv.DictReader(f):
            hid = r["id"].strip()
            if not hid or hid.startswith("#") or hid in EXCLUDE:
                continue
            s = ships.get(hid)
            if not s or s.get("hullSize") not in ROLE_BY_SIZE:
                continue
            hints = {h.strip() for h in r["hints"].split(",") if h.strip()}
            tags = {t.strip() for t in r["tags"].split(",") if t.strip()}
            builtins = set(s.get("builtInMods", []))
            if tags & EXCLUDE_TAGS or hints & EXCLUDE_HINTS or builtins & EXCLUDE_BUILTINS:
                continue
            if "/phase/" in s.get("spriteName", ""):
                continue
            rows.append({
                "id": hid,
                "name": r["name"],
                "size": s["hullSize"],
                "fp": int(r["fleet pts"] or 0),
                "sprite": s["spriteName"],
                "engines": len(s.get("engineSlots", [])),
                "bays": int(r["fighter bays"] or 0),
            })
    order = {"FRIGATE": 0, "DESTROYER": 1, "CRUISER": 2, "CAPITAL_SHIP": 3}
    rows.sort(key=lambda x: (order[x["size"]], x["id"]))
    return rows


def vanilla_variants():
    """hullId -> [variant json] for the goal variants (any variant when a hull has none)."""
    by_hull = {}
    for p in glob.glob(os.path.join(CORE, "data/variants/**/*.variant"), recursive=True):
        v = load_json(p)
        by_hull.setdefault(v["hullId"], []).append(v)
    out = {}
    for hull, vs in by_hull.items():
        keep = [v for v in vs if not re.search(r"_(Starting|Tutorial)$", v["variantId"])]
        goal = [v for v in keep if v.get("goalVariant")]
        out[hull] = goal or keep
    return out


# ---------------------------------------------------------------- the palette

def threat_reference():
    """Luminance quantiles and luminance->rgb ramp of vanilla's Threat ship sprites."""
    px = []
    for p in sorted(glob.glob(os.path.join(CORE, "graphics/ships/threat/*.png"))):
        if "fragment" in os.path.basename(p):
            continue
        im = np.asarray(Image.open(p).convert("RGBA")).astype(np.float64)
        px.append(im[im[..., 3] > 200][:, :3])
    px = np.concatenate(px)
    lum = luma(px)
    quantiles = np.quantile(lum, np.linspace(0, 1, 257))
    centres = np.arange(4, 256, 8, dtype=np.float64)
    ramp = np.zeros((len(centres), 3))
    for i, c in enumerate(centres):
        m = (lum >= c - 4) & (lum < c + 4)
        if m.sum() >= 15:
            ramp[i] = np.median(px[m], axis=0)
        else:
            ramp[i] = np.nan
    # fill the ends by extending the nearest sampled bucket along the grey axis
    for ch in range(3):
        col = ramp[:, ch]
        ok = ~np.isnan(col)
        ramp[:, ch] = np.interp(centres, centres[ok], col[ok])
    return quantiles, centres, ramp


def luma(rgb):
    return 0.299 * rgb[..., 0] + 0.587 * rgb[..., 1] + 0.114 * rgb[..., 2]


def value_noise(h, w, cell, rng):
    """Smooth noise in [-1, 1] from a random grid upsampled bicubically."""
    gh, gw = max(2, h // cell + 2), max(2, w // cell + 2)
    grid = rng.random((gh, gw)).astype(np.float32)
    im = Image.fromarray((grid * 255).astype(np.uint8)).resize((w, h), Image.BICUBIC)
    return np.asarray(im).astype(np.float64) / 127.5 - 1.0


def convert_sprite(img, ref, seed):
    quantiles, centres, ramp = ref
    rng = np.random.default_rng(seed)
    arr = np.asarray(img.convert("RGBA")).astype(np.float64)
    h, w = arr.shape[:2]
    alpha = arr[..., 3]
    rgb = arr[..., :3]
    solid = alpha > 128
    if solid.sum() < 10:
        return img

    # 1. brightness: match the hull's luminance distribution to the Threat's
    lum = luma(rgb)
    src_q = np.quantile(lum[solid], np.linspace(0, 1, 257))
    matched = np.interp(lum, src_q, quantiles)
    lum2 = 0.96 * matched + 0.04 * lum
    # the accents, mottle and glow below all add light; take it off here first
    lum2 = 255.0 * (np.clip(lum2, 0, 255) / 255.0) ** 1.12

    # 2. colour from the Threat ramp at that brightness
    out = np.stack([np.interp(lum2, centres, ramp[:, ch]) for ch in range(3)], axis=-1)

    # 3. faction paint -> amber accent (the hive's glow colour), same brightness
    mx = rgb.max(axis=-1)
    mn = rgb.min(axis=-1)
    sat = (mx - mn) / np.maximum(mx, 1.0)
    amber = np.array([142.0, 110.0, 80.0])
    amber_l = luma(amber)
    accent = np.clip(lum2[..., None] / amber_l * amber, 0, 255)
    wgt = np.clip((sat - 0.3) / 0.45, 0, 1) * np.clip(lum / 60.0, 0, 1) * 0.5
    out = out * (1 - wgt[..., None]) + accent * wgt[..., None]

    # 4. mottle: two octaves of low-frequency noise, +-10 percent
    cell = max(6, min(h, w) // 7)
    n = 0.65 * value_noise(h, w, cell, rng) + 0.35 * value_noise(h, w, max(3, cell // 3), rng)
    out = out * (1.0 + 0.10 * n[..., None])

    # 5. glow nodes: a few amber hatches well inside the hull, mirrored left-right
    interior = np.asarray(Image.fromarray((solid * 255).astype(np.uint8)).filter(ImageFilter.MinFilter(7))) > 0
    ys, xs = np.nonzero(interior[:, : w // 2 + 1])
    if len(xs) > 0:
        count = max(1, int(round(np.sqrt(solid.sum()) / 26.0)))
        chosen = []
        order = rng.permutation(len(xs))
        for i in order:
            y, x = ys[i], xs[i]
            if all((y - cy) ** 2 + (x - cx) ** 2 >= 12 ** 2 for cy, cx in chosen):
                chosen.append((y, x))
            if len(chosen) >= count:
                break
        yy, xx = np.mgrid[0:h, 0:w]
        glow = np.array([226.0, 182.0, 124.0])
        for cy, cx in chosen:
            r = rng.uniform(1.6, 2.8) * (1.0 + np.sqrt(solid.sum()) / 400.0)
            for gx in {cx, w - 1 - cx}:
                d2 = (yy - cy) ** 2 + (xx - gx) ** 2
                k = np.exp(-d2 / (2 * r * r))
                k[~solid] = 0
                out = out * (1 - 0.9 * k[..., None]) + glow * (0.9 * k[..., None])

    out = np.clip(out, 0, 255)
    res = np.concatenate([out, alpha[..., None]], axis=-1).astype(np.uint8)
    # fully transparent pixels keep vanilla's colour so edge blending is unchanged
    res[alpha == 0, :3] = arr[alpha == 0, :3].astype(np.uint8)
    return Image.fromarray(res, "RGBA")


# ---------------------------------------------------------------- output files

def skin_json(hull):
    hid = PREFIX + hull["id"] + SUFFIX
    engines = {str(i): {"style": "THREAT"} for i in range(hull["engines"])}
    return {
        "baseHullId": hull["id"],
        "skinHullId": hid,
        "hullName": hull["name"] + " (Converted)",
        "descriptionId": hull["id"],
        "descriptionPrefix": DESCRIPTION_PREFIX,
        "tags": TAGS,
        "tech": "Threat",
        "spriteName": f"{SPRITE_DIR}/{hull['id']}{SUFFIX}.png",
        "addHints": ["UNBOARDABLE"],
        "builtInMods": BUILT_IN_MODS,
        "removeWeaponSlots": [],
        "removeEngineSlots": [],
        "removeBuiltInMods": [],
        "removeBuiltInWeapons": [],
        "builtInWeapons": {},
        "engineSlotChanges": engines,
    }


def write_json(path, obj, header):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("# " + header + "\n")
        json.dump(obj, f, indent=4)
        f.write("\n")


def clone_variant(v, hull):
    hid = PREFIX + hull["id"] + SUFFIX
    suffix = v["variantId"]
    if suffix.startswith(hull["id"] + "_"):
        suffix = suffix[len(hull["id"]) + 1:]
    c = json.loads(json.dumps(v))
    c["hullId"] = hid
    c["variantId"] = f"{hid}_{suffix}"
    c["goalVariant"] = True
    return c


def write_roles(roles):
    path = os.path.join(MOD, ROLES_FILE)
    text = open(path, encoding="utf-8").read()
    lines = []
    for role, ids in roles.items():
        lines.append(f'\t"{role}": {{')
        for i, vid in enumerate(ids):
            comma = "," if i < len(ids) - 1 else ""
            lines.append(f'\t\t"{vid}": 1{comma}')
        lines.append("\t},")
    block = ROLES_BEGIN + "\n" + "\n".join(lines) + "\n" + ROLES_END + "\n"
    if ROLES_BEGIN in text and ROLES_END in text:
        a = text.index(ROLES_BEGIN)
        b = text.index(ROLES_END) + len(ROLES_END) + 1
        text = text[:a] + block + text[b:]
    else:
        # before the closing brace; the preceding entry must already end with a comma
        end = text.rstrip().rfind("}")
        body = text[:end].rstrip()
        if not body.endswith(","):
            body += ","
        text = body + "\n" + block + "}\n"
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def clean_outputs():
    for pattern in (f"{SPRITE_DIR}/*{SUFFIX}.png", f"{SKIN_DIR}/{PREFIX}*{SUFFIX}.skin",
                    f"{VARIANT_DIR}/*.variant"):
        for p in glob.glob(os.path.join(MOD, pattern)):
            os.remove(p)


def preview(hulls, ref, picks=("lasher", "hammerhead", "eagle", "onslaught")):
    """Side-by-side vanilla / converted strip, beside two vanilla Threat hulls, at half size."""
    tiles = []
    for hid in picks:
        h = next((x for x in hulls if x["id"] == hid), None)
        if not h:
            continue
        a = Image.open(os.path.join(CORE, h["sprite"])).convert("RGBA")
        b = Image.open(os.path.join(MOD, SPRITE_DIR, hid + SUFFIX + ".png")).convert("RGBA")
        tiles += [a, b]
    for p in ("threat_skirmish.png", "threat_assault_unit.png"):
        tiles.append(Image.open(os.path.join(CORE, "graphics/ships/threat", p)).convert("RGBA"))
    scale = 0.5
    tiles = [t.resize((max(1, int(t.width * scale)), max(1, int(t.height * scale))), Image.LANCZOS) for t in tiles]
    gap = 12
    W = sum(t.width for t in tiles) + gap * (len(tiles) + 1)
    H = max(t.height for t in tiles) + 2 * gap
    sheet = Image.new("RGBA", (W, H), (20, 22, 28, 255))
    x = gap
    for t in tiles:
        sheet.alpha_composite(t, (x, (H - t.height) // 2))
        x += t.width + gap
    out = os.path.join(MOD, "tools/converted-hulls/preview.png")
    sheet.save(out)
    print("preview", out, sheet.size)


def main():
    hulls = vanilla_hulls()
    variants = vanilla_variants()
    ref = threat_reference()
    clean_outputs()
    roles = {r: [] for r in ROLE_BY_SIZE.values()}
    for i, h in enumerate(hulls):
        img = Image.open(os.path.join(CORE, h["sprite"]))
        out = convert_sprite(img, ref, seed=1000 + i)
        os.makedirs(os.path.join(MOD, SPRITE_DIR), exist_ok=True)
        out.save(os.path.join(MOD, SPRITE_DIR, h["id"] + SUFFIX + ".png"))
        write_json(os.path.join(MOD, SKIN_DIR, PREFIX + h["id"] + SUFFIX + ".skin"), skin_json(h),
                   "GENERATED by tools/converted-hulls/gen.py from vanilla's " + h["id"] + " - do not edit by hand")
        n = 0
        for v in variants.get(h["id"], []):
            c = clone_variant(v, h)
            write_json(os.path.join(MOD, VARIANT_DIR, c["variantId"] + ".variant"), c,
                       "GENERATED by tools/converted-hulls/gen.py from vanilla's " + v["variantId"])
            roles[ROLE_BY_SIZE[h["size"]]].append(c["variantId"])
            n += 1
        print(f"{h['size']:12s} {h['id']:14s} fp {h['fp']:3d} engines {h['engines']:2d} variants {n}")
    write_roles(roles)
    print("hulls", len(hulls), "variants", sum(len(v) for v in roles.values()))
    if "--preview" in sys.argv:
        preview(hulls, ref)


if __name__ == "__main__":
    main()
